"""gen_sigs.py COGMIND.exe include/cogmind.h > sigs/cogmind.sigs

Builds byte signatures (AOB patterns, as in UE4SS / patternsleuth) for every ADDR_* / FN_* address in
cogmind.h, so the mod can find them again in a different build of the game. The output is a plain
text sidecar: the build compiles it in, and a copy in <game>/hack/sigs.txt replaces it at runtime.

  ADDR_* (data): a code site that uses the address as an absolute operand (32-bit code addresses
                 globals directly: mov ecx,[0xcf0d28] = 8B 0D 28 0D CF 00). Pattern = bytes around it
                 with the operand wildcarded; the runtime reads the operand back out of the match.
  FN_*  (code):  the function's first bytes (with the padding before it); operand = offset of the
                 function start inside the match.

Bytes that move between builds are wildcarded: the operand itself, other image addresses (absolute
operands that look like VAs in the image) and rel32 call/jmp displacements. Each pattern grows until
it matches exactly once in .text. Up to 3 independent sites are kept per address (a game update can
break one site and not the others).
"""
import re, struct, sys

exe, header = sys.argv[1], sys.argv[2]
b = open(exe, 'rb').read()
pe = struct.unpack_from('<I', b, 0x3c)[0]
nsec = struct.unpack_from('<H', b, pe + 6)[0]
opt = struct.unpack_from('<H', b, pe + 20)[0]
base = struct.unpack_from('<I', b, pe + 24 + 28)[0]
size_img = struct.unpack_from('<I', b, pe + 24 + 56)[0]
stamp = struct.unpack_from('<I', b, pe + 8)[0]
text = None
for i in range(nsec):
    s = pe + 24 + opt + i * 40
    name = b[s:s + 8].rstrip(b'\0')
    vs, va, rs, ro = struct.unpack_from('<IIII', b, s + 8)
    if name == b'.text': text = (base + va, b[ro:ro + min(vs, rs)])
tva, T = text
LO, HI = base, base + size_img

targets = []
for line in open(header):
    m = re.match(r'\s*X\(((ADDR|FN)_\w+),\s*(0x[0-9a-fA-F]+)\)', line)     # the CM_ADDRESSES list
    if m: targets.append((m.group(1), int(m.group(3), 16)))

def movable(win, k):
    """which byte positions in win are wildcards (other image VAs, rel32 after E8/E9)."""
    wild = set()
    for j in range(len(win) - 3):
        v = struct.unpack_from('<I', win, j)[0]
        if LO <= v < HI and v != 0: wild.update(range(j, j + 4))
    for j in range(len(win)):                      # rel32 call/jmp, also when cut off by the window end
        if win[j] in (0xE8, 0xE9): wild.update(range(j + 1, min(j + 5, len(win))))
    return wild

def matches(pat, mask, limit=2):
    # anchor on the longest run of fixed bytes
    best, bi, run, ri = 0, 0, 0, 0
    for j, m in enumerate(mask):
        if m: run += 1; ri = j - run + 1
        else: run = 0
        if run > best: best, bi = run, ri
    if best < 2: return 99
    anchor = bytes(pat[bi:bi + best])
    n, pos = 0, T.find(anchor)
    while pos >= 0:
        st = pos - bi
        if 0 <= st and st + len(pat) <= len(T) and all(not mask[j] or T[st + j] == pat[j] for j in range(len(pat))):
            n += 1
            if n >= limit: return n
        pos = T.find(anchor, pos + 1)
    return n

def fmt(pat, mask):
    return ' '.join('%02X' % p if m else '??' for p, m in zip(pat, mask))

def sig_for_site(at, operand_len):
    """at = offset in T of the operand (or of the function start when operand_len == 0)."""
    for before in (2, 3, 4, 6, 8, 10, 12):
        for after in (4, 6, 8, 12, 16, 20, 24, 32, 40, 48, 64):
            st, en = at - before, at + operand_len + after
            if st < 0 or en > len(T): continue
            win = T[st:en]
            wild = movable(win, before)
            mask = [j not in wild for j in range(len(win))]
            for j in range(before, before + operand_len): mask[j] = False
            if sum(mask) < 6: continue
            if matches(win, mask) == 1: return win, mask, before
    return None

out = []
for name, addr in targets:
    sigs = []
    if name.startswith('FN_'):
        at = addr - tva
        if 0 <= at < len(T):
            r = sig_for_site(at, 0)
            if r: sigs.append((r, r[2]))          # operand = offset of the function start in the match
    else:
        needle = struct.pack('<I', addr)
        pos = T.find(needle)
        while pos >= 0 and len(sigs) < 3:
            r = sig_for_site(pos, 4)
            if r: sigs.append((r, r[2]))
            pos = T.find(needle, pos + 1)
    out.append((name, addr, sigs))

DERIVED = {'ADDR_UI_ROOT': ('ADDR_DISPLAY', 0x6c), 'ADDR_MAP_H': ('ADDR_MAP_W', 4), 'ADDR_MAP_CELLS': ('ADDR_MAP_W', 8),
           'ADDR_PROP_REGISTRY': ('ADDR_ENT_REGISTRY', 4), 'ADDR_LOC_REGISTRY': ('ADDR_ENT_REGISTRY', 0x14)}
addrs = dict(targets)

print("""# Byte signatures for the addresses in include/cogmind.h (read by src/game/sigs.c).
# Generated by tools/re/gen_sigs.py from COGMIND.exe. Put a copy in <game>/hack/sigs.txt to use it
# instead of the built-in one.
#
#   build <PE timestamp> <image size>        the build this file was generated from
#   <name> data <offset> <pattern>           the address is the 32-bit value at <offset> in the match
#   <name> code <offset> <pattern>           the function starts at <offset> in the match
#   <name> = <base> + <delta>                derived from another address
#
# Patterns are hex bytes, ?? matches any byte. Each one must match exactly once in .text.
# Several lines for one name are separate code sites; they must agree.
""")
print('build %08x %x' % (stamp, size_img))
missing = []
for name, addr, sigs in out:
    if not sigs: missing.append(name)
    if sigs: print()
    for (win, mask, before), op in sigs:
        print('%-22s %s %d  %s' % (name, 'code' if name.startswith('FN_') else 'data', op, fmt(win, mask)))
print()
for n, (bn, dl) in DERIVED.items():
    assert addrs[n] == addrs[bn] + dl, n
    print('%-22s = %s + %#x' % (n, bn, dl))
missing = [m for m in missing if m not in DERIVED]
if missing:
    print('\n# no unique code site: %s' % ', '.join(missing))
print('%d/%d addresses have signatures' % (len(out) - len(missing), len(out)), file=sys.stderr)
